import { afterCommit, requireScope } from '../tenancy/tenant-context.js';
import { BadRequestException } from '@nestjs/common';
import sharp from 'sharp';
import * as fs from 'fs';
import * as path from 'path';
import * as crypto from 'crypto';

/**
 * Converts `buffer` to both WebP and AVIF, saves them under `uploads/`,
 * and returns the WebP filename.  The AVIF file is always written alongside
 * as `<uuid>.avif` so callers can derive its path by swapping the extension.
 */
export async function uploadLocalImage(buffer: Buffer, _folder = 'StyleDesk', maxDimension = 1000): Promise<string> {
  if (buffer.length > 12 * 1024 * 1024) throw new BadRequestException('Images must be 12 MB or smaller');
  const uploadsDir = path.join(process.cwd(), 'uploads', requireScope().tenantId);
  await fs.promises.mkdir(uploadsDir, { recursive: true });

  const uuid = crypto.randomUUID();
  const webpFileName = `${uuid}.webp`;
  const avifFileName = `${uuid}.avif`;
  const webpPath = path.join(uploadsDir, webpFileName);
  const avifPath = path.join(uploadsDir, avifFileName);

  // Use a single decode pass — Sharp pipelines share the decoded raster
  const pipeline = sharp(buffer, { limitInputPixels: 25_000_000 })
    .rotate() // Auto-rotate based on EXIF orientation
    .resize(maxDimension, maxDimension, { fit: 'inside', withoutEnlargement: true });

  await Promise.all([
    pipeline.clone().webp({ quality: 82 }).toFile(webpPath),
    pipeline.clone().avif({ quality: 60, effort: 4 }).toFile(avifPath),
  ]);

  return `${requireScope().tenantId}/${webpFileName}`; // Callers store this; AVIF lives at same UUID with .avif extension
}

export async function uploadLocalVideo(buffer: Buffer, _folder = 'StyleDesk'): Promise<string> {
  const uploadsDir = path.join(process.cwd(), 'uploads', requireScope().tenantId);
  await fs.promises.mkdir(uploadsDir, { recursive: true });

  const fileName = `${crypto.randomUUID()}.mp4`;
  const filePath = path.join(uploadsDir, fileName);

  await fs.promises.writeFile(filePath, buffer);
  return `${requireScope().tenantId}/${fileName}`;
}

export async function deleteLocalFile(url: string, resourceType: 'image' | 'video' = 'image'): Promise<void> {
  if (!url) return;
  const tenantId = requireScope().tenantId;
  const pathname = url.replace(/^https?:\/\/[^/]+/, '').replace(/^\/?uploads\//, '');
  if (!pathname.startsWith(`${tenantId}/`) || pathname.includes('..')) throw new BadRequestException('File belongs to another tenant');
  afterCommit(async () => {
  try {
    const uploadsDir = path.join(process.cwd(), 'uploads', tenantId);
    const fileName = path.basename(pathname);
    const filePath = path.join(uploadsDir, fileName);

    await fs.promises.unlink(filePath).catch(() => undefined);

    // For images, also remove the companion AVIF / WebP sidecar generated by uploadLocalImage
    if (resourceType === 'image') {
      const ext = path.extname(fileName).toLowerCase();
      const base = path.basename(fileName, ext);
      const companions = ext === '.webp'
        ? [`${base}.avif`]
        : ext === '.avif'
          ? [`${base}.webp`]
          : [];
      for (const companion of companions) {
        const companionPath = path.join(uploadsDir, companion);
        await fs.promises.unlink(companionPath).catch(() => undefined);
      }
    }
  } catch (error) {
    console.error('Error deleting local file:', error);
  }
  });
}
